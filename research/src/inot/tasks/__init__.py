# SWE-bench Lite (optional; needs the `datasets` install + network)
# ---------------------------------------------------------------------------
def load_swebench_lite(n: Optional[int] = None) -> list[Task]:
    """Load SWE-bench Lite (Jimenez et al. 2024). Optional: returns [] gracefully
    if the dataset is unavailable so the rest of the suite still runs."""
    try:
        from datasets import load_dataset  # type: ignore
        ds = load_dataset("princeton-nlp/SWE-bench_Lite", split="test")
    except Exception:
        return []
    out: list[Task] = []
    items = ds if n is None else ds.select(range(min(n, len(ds))))
    for r in items:
        out.append(
            Task(
                task_id=r["instance_id"],
                prompt=r.get("problem_statement", "")[:8000],
                context=r.get("hints_text", "") or "",
                # SWE-bench evaluation is heavy (real repo + container). Here we
                # use a degenerate 'check' that always succeeds; cost/token
                # statistics remain meaningful, but pass@1 will not. Experiments
                # that need real SWE-bench grading should call the upstream
                # harness — see docs/e4.md.
                test_code="def check(_):\n    pass\n",
                entry_point="solve",
                suite="swebench_lite",
                metadata={"raw": {k: r[k] for k in ("instance_id", "repo", "base_commit")}},
            )
        )
    return out


