# Synthetic Tool-Use Suite (defined in §3.2 / Appendix A of the article)
# ---------------------------------------------------------------------------
def build_synthetic_tool_use_suite(n: int = 50, seed: int = 42) -> list[Task]:
    """Procedural generator for the article's Synthetic Tool-Use Suite.

    Each task asks the agent to independently solve k ∈ {2,3,4} fully
    independent subtasks (parallelism degree p_||). Verification is set up so
    the test code checks each sub-result with a separate ``check`` clause —
    this is exactly the regime in which H3 predicts that Classical-MAS wins
    by parallelising sub-roles, while Hybrid-INoT's serial inner loop cannot.
    """
    rng = random.Random(seed)
    tasks: list[Task] = []
    for i in range(n):
        k = rng.choice([2, 3, 4])
        ops: list[tuple[str, int, int]] = []
        for j in range(k):
            a = rng.randint(2, 30)
            b = rng.randint(2, 30)
            op = rng.choice(["add", "mul", "sub"])
            ops.append((op, a, b))
        prompt = (
            "Implement a module exposing the following independent helper functions.\n"
            "Each function MUST be implemented independently from the others.\n"
            "Return the complete Python source defining all functions in one block.\n\n"
        )
        for j, (op, a, b) in enumerate(ops):
            prompt += f"{j+1}. def f{j}() -> int:  # must return {_ref(op, a, b)} = {_apply(op, a, b)}\n"
        # Fake context: large doc string (parallel tools H3 doesn't need long context, but
        # we add a minimal background so token counts are non-degenerate).
        ctx = (
            "# Project documentation\n"
            "# These helpers are used by independent CI jobs; correctness of one\n"
            "# is independent from any other.\n"
        )
        # Test code calls every f0..f{k-1} and asserts on it.
        check_lines = "\n    ".join(
            f"assert candidate.f{j}() == {_apply(op, a, b)}, 'f{j} wrong'"
            for j, (op, a, b) in enumerate(ops)
        )
        test_code = (
            "import types\n"
            "def check(_unused):\n"
            "    candidate = types.SimpleNamespace()\n"
            + "\n".join(f"    candidate.f{j} = f{j}" for j in range(k))
            + f"\n    {check_lines}\n"
        )
        tasks.append(
            Task(
                task_id=f"synthetic/{i:04d}",
                prompt=prompt,
                context=ctx,
                test_code=test_code,
                entry_point="f0",
                suite="synthetic_tools",
                metadata={
                    "parallelism": k,
                    "requires_tool": True,
                    "force_hybrid_internal": True,
                    "ops": ops,
                    "tool_latency_ms": [rng.randint(80, 180) for _ in range(k)],
                },
            )
        )
    return tasks


def _apply(op: str, a: int, b: int) -> int:
    if op == "add":
        return a + b
    if op == "mul":
        return a * b
    return a - b


def _ref(op: str, a: int, b: int) -> str:
    sym = {"add": "+", "mul": "*", "sub": "-"}[op]
    return f"{a} {sym} {b}"
